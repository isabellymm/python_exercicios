#Faça um Programa que peça as 4 notas bimestrais e mostre a média.

nota1 = float (input('Informe as Notas do 1 bim : '))
nota2 = float (input('Informe as Notas do 2 bim : '))
nota3 = float (input('Informe as Notas do 3 bim : '))
nota4 = float (input('Informe as Notas do 4 bim : '))

media = ((nota1 + nota2 + nota3 + nota4 ) / 4 )

print ('A média é de : ',media)